import { api } from "../api/client";
import type { CitationOut } from "../api/types";

/** Side panel for one citation: document, page/section and the stored original excerpt. */
export function SourcePanel({ citation, onClose }: { citation: CitationOut; onClose: () => void }) {
  return (
    <aside
      className="flex h-full w-96 shrink-0 flex-col border-l border-neutral-200 bg-neutral-50 max-lg:absolute max-lg:inset-y-0 max-lg:right-0 max-lg:z-20 max-lg:shadow-xl"
      aria-label="Source"
    >
      <div className="flex items-start justify-between gap-2 border-b border-neutral-200 p-4">
        <div className="min-w-0">
          <div className="text-xs font-semibold uppercase tracking-wide text-emerald-700">
            Source {citation.marker}
          </div>
          <div className="truncate font-medium" title={citation.document_name}>
            {citation.document_name}
          </div>
          <div className="text-sm text-neutral-600">{citation.location}</div>
        </div>
        <button
          onClick={onClose}
          className="rounded px-2 py-1 text-sm text-neutral-500 hover:bg-neutral-200"
          aria-label="Close source panel"
        >
          ✕
        </button>
      </div>
      <div className="flex-1 overflow-y-auto p-4">
        <div className="mb-2 text-xs text-neutral-500">
          Original text from the document (not generated by the model):
        </div>
        <blockquote className="whitespace-pre-wrap border-l-4 border-emerald-400 bg-white p-3 text-sm leading-relaxed shadow-sm">
          {citation.excerpt}
        </blockquote>
        {citation.score !== null && citation.score !== undefined && (
          <div className="mt-3 text-xs text-neutral-500">
            Similarity {citation.score.toFixed(3)}
          </div>
        )}
      </div>
      <div className="border-t border-neutral-200 p-4 text-sm">
        {citation.document_id ? (
          <a
            href={api.fileUrl(citation.document_id)}
            target="_blank"
            rel="noreferrer"
            className="text-blue-700 underline"
          >
            Open original file
          </a>
        ) : (
          <span className="text-neutral-500">The document has since been deleted.</span>
        )}
      </div>
    </aside>
  );
}
